// Builds src/components/landing/zoneCountries.ts: the country of every time zone, so the landing
// globe can name the visitor's country from the time zone their browser reports. Uses the time
// zone and country data built into Node (CLDR), so nothing is downloaded, and the old zone names
// in timezones.ts, so both the old and the current name of a zone are found.
//
// Run: npm run data:zone-countries
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUTPUT = fileURLToPath(new URL("../src/components/landing/zoneCountries.ts", import.meta.url));
const ZONES_FILE = fileURLToPath(new URL("../src/components/landing/timezones.ts", import.meta.url));

// Shorter or plainer than CLDR's own English names.
const NAMES = {
  BA: "Bosnia and Herzegovina",
  CC: "Cocos Islands",
  CD: "DR Congo",
  CG: "Republic of the Congo",
  CI: "Côte d'Ivoire",
  HK: "Hong Kong",
  MM: "Myanmar",
  MO: "Macao",
  PN: "Pitcairn Islands",
  PS: "Palestine",
};

const english = new Intl.DisplayNames(["en"], { type: "region" });
const plain = (code) => NAMES[code] ?? english.of(code).replace(/ & /g, " and ").replace(/^St\. /, "Saint ");

const zoneCountry = {};
const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
for (const a of letters) {
  for (const b of letters) {
    const code = a + b;
    const name = english.of(code);
    if (!name || name === code) continue;
    const locale = new Intl.Locale(`und-${code}`);
    // Old codes (SU, ZR, YU…) are renamed to today's country; only today's code is kept.
    if (locale.region !== code) continue;
    for (const zone of locale.getTimeZones?.() ?? []) zoneCountry[zone] = code;
  }
}

// Every zone timezones.ts knows, under its own name too: Node files Asia/Kolkata under its older
// name Asia/Calcutta, and Africa/Asmara under Africa/Asmera.
const zonesFile = readFileSync(ZONES_FILE, "utf8");
const known = Object.keys(JSON.parse(/TIME_ZONES: Record<string, \[number, number\]> = (\{.*\});/.exec(zonesFile)[1]));
const aliases = JSON.parse(/TIME_ZONE_ALIASES: Record<string, string> = (\{.*\});/.exec(zonesFile)[1]);
const nodeName = (zone) => {
  try {
    return new Intl.DateTimeFormat("en", { timeZone: zone }).resolvedOptions().timeZone;
  } catch {
    return zone;
  }
};
for (const zone of [...known, ...Object.keys(aliases)]) {
  if (!zoneCountry[zone] && zoneCountry[nodeName(zone)]) zoneCountry[zone] = zoneCountry[nodeName(zone)];
}
const missing = known.filter((zone) => !zoneCountry[zone]);
if (missing.length) throw new Error(`No country for ${missing.join(", ")}`);

const zones = Object.fromEntries(Object.entries(zoneCountry).sort(([a], [b]) => a.localeCompare(b)));
const names = Object.fromEntries([...new Set(Object.values(zoneCountry))].sort().map((code) => [code, plain(code)]));
const source = `// Generated by scripts/build-zone-countries.mjs from the time zone data built into Node (CLDR). Do not edit.
// The country of each time zone, and each country's name.

export const ZONE_COUNTRY: Record<string, string> = ${JSON.stringify(zones)};

export const COUNTRY_NAMES: Record<string, string> = ${JSON.stringify(names)};
`;
writeFileSync(OUTPUT, source);
console.log(`Wrote ${Object.keys(zones).length} zones in ${Object.keys(names).length} countries (${(source.length / 1024).toFixed(1)} KB) → ${OUTPUT}`);
