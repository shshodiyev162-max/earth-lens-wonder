// Builds src/components/landing/timezones.ts: the main city of every time zone
// (IANA tz database, public domain), so the landing globe can mark the visitor's
// part of the world from the time zone their browser reports. No location
// permission is needed and nothing leaves the device.
//
// Run: npm run data:timezones
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BASE = "https://raw.githubusercontent.com/eggert/tz/main";
const OUTPUT = fileURLToPath(new URL("../src/components/landing/timezones.ts", import.meta.url));

async function download(name) {
  const response = await fetch(`${BASE}/${name}`);
  if (!response.ok) throw new Error(`${name}: download failed (${response.status})`);
  return response.text();
}

// ISO 6709 "+4120+06918" or "+412000+0691800" → degrees.
function parseCoordinates(text) {
  const match = /^([+-]\d{4,6})([+-]\d{5,7})$/.exec(text);
  if (!match) throw new Error(`Bad coordinates: ${text}`);
  const toDegrees = (part, degreeDigits) => {
    const sign = part[0] === "-" ? -1 : 1;
    const digits = part.slice(1);
    const d = Number(digits.slice(0, degreeDigits));
    const m = Number(digits.slice(degreeDigits, degreeDigits + 2));
    const s = Number(digits.slice(degreeDigits + 2) || 0);
    return sign * (d + m / 60 + s / 3600);
  };
  return [toDegrees(match[1], 2), toDegrees(match[2], 3)];
}

const zones = new Map();
for (const line of (await download("zone.tab")).split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [, coordinates, name] = line.split("\t");
  const [lat, lon] = parseCoordinates(coordinates);
  zones.set(name, [Math.round(lat * 10) / 10, Math.round(lon * 10) / 10]);
}

// Old names browsers still report (Asia/Calcutta, Europe/Kiev…) point at the current zone.
const aliases = {};
for (const line of (await download("backward")).split("\n")) {
  const match = /^Link\s+(\S+)\s+(\S+)/.exec(line);
  if (match && zones.has(match[1]) && !zones.has(match[2])) aliases[match[2]] = match[1];
}

const table = Object.fromEntries([...zones].sort(([a], [b]) => a.localeCompare(b)));
const source = `// Generated by scripts/build-timezones.mjs from the IANA tz database (public domain). Do not edit.
// The main city of each time zone, as [latitude, longitude] in degrees.

export const TIME_ZONES: Record<string, [number, number]> = ${JSON.stringify(table)};

/** Older names some browsers report, mapped to the current zone. */
export const TIME_ZONE_ALIASES: Record<string, string> = ${JSON.stringify(aliases)};
`;
writeFileSync(OUTPUT, source);
console.log(`Wrote ${zones.size} zones and ${Object.keys(aliases).length} aliases (${(source.length / 1024).toFixed(1)} KB) → ${OUTPUT}`);
